"""Read the walls of a ``.world`` file and plan a route through them.

The maze in ``maze_description/worlds`` is generated by
``tools/generate_maze.py``: one ``<model name="maze_wall_###">`` per wall box,
each a ``<box>`` of ``WALL_T x WALL_L x WALL_H`` centred on a ``<pose>``.

Pure pursuit used to carry a hard-coded ``"x,y;x,y;..."`` polyline in its
launch file.  That only ever matched the maze it was written for: load another
seed and the very first leg of the path runs through a wall, so the robot
drives into the wall a few centimetres after start.  This module removes that
coupling -- the node reads the same world file Gazebo loads, rebuilds the
occupancy grid from the wall boxes and plans the route itself.

No rclpy here: it is plain python plus numpy/scipy, so the unit tests can call
it without a ROS graph.
"""

import math
import xml.etree.ElementTree as ET

from .race_planner import DEFAULT_CFG, GridMap, astar, shortcut, simplify


def parse_world(path):
    """Return ``[(cx, cy, sx, sy, name), ...]`` for every maze wall box."""
    root = ET.parse(path).getroot()
    segments = []
    for model in root.iter('model'):
        name = model.get('name', '')
        if not name.startswith('maze_wall'):
            continue
        pose = _floats(model.findtext('pose'))
        size = None
        for box in model.iter('box'):
            size = _floats(box.findtext('size'))
            break
        if pose is None or size is None or len(pose) < 2 or len(size) < 2:
            raise RuntimeError(f'{path}: wall {name!r} has no usable pose/size')
        segments.append((pose[0], pose[1], size[0], size[1], name))
    if not segments:
        raise RuntimeError(
            f'{path}: no <model name="maze_wall_*"> boxes found -- is this the '
            'maze world?')
    return segments


def _floats(text):
    if not text:
        return None
    return [float(tok) for tok in text.replace(',', ' ').split()]


def world_bounds(segments, margin=0.30):
    """Bounding box of the walls, grown by ``margin`` (xmin, xmax, ymin, ymax)."""
    xs0 = min(cx - sx / 2.0 for cx, cy, sx, sy, _ in segments)
    xs1 = max(cx + sx / 2.0 for cx, cy, sx, sy, _ in segments)
    ys0 = min(cy - sy / 2.0 for cx, cy, sx, sy, _ in segments)
    ys1 = max(cy + sy / 2.0 for cx, cy, sx, sy, _ in segments)
    return (xs0 - margin, xs1 + margin, ys0 - margin, ys1 + margin)


def route_from_world(world, start, goal, cfg=None):
    """Plan a waypoint polyline from ``start`` to ``goal`` inside ``world``.

    The occupancy grid is rebuilt at 5 cm from the wall boxes, walls are
    inflated by ``obstacle_radius`` while searching, and the resulting cell
    path is simplified to a handful of corners -- the same
    ``astar``/``simplify`` that the race planner uses, so the route keeps a
    constant clearance instead of hugging the wall.
    """
    segments = parse_world(world)
    base = dict(DEFAULT_CFG, **(cfg or {}))
    base['bounds'] = world_bounds(segments)
    gmap = GridMap.from_walls(segments, base)

    cells = astar(gmap, tuple(start), tuple(goal), base)
    if not cells or len(cells) < 2:
        raise RuntimeError(
            f'{world}: no route from {tuple(start)} to {tuple(goal)}')
    # string pulling first (every shortcut is clearance checked), then drop the
    # redundant collinear corners; simplify() alone would not check walls
    route = simplify(shortcut(gmap, cells, base),
                     tol=base.get('simplify_tol', 0.08))
    # keep the exact endpoints: simplify() already keeps them, but a start that
    # sits in a "tight" cell may have been nudged to the nearest drivable cell.
    route[0] = tuple(start)
    route[-1] = tuple(goal)
    return route, len(segments)


def segment_clearance(segments, a, b, step=0.02):
    """Smallest distance from the segment ``a``->``b`` to any wall box [m].

    Used as a cheap pre-flight check: a pure P controller can only drive in a
    straight line, so if this is smaller than the robot radius the goal is not
    reachable without planning.
    """
    dist = math.hypot(b[0] - a[0], b[1] - a[1])
    n = max(2, int(dist / step))
    best = float('inf')
    where = None
    for k in range(n + 1):
        t = k / n
        x = a[0] + (b[0] - a[0]) * t
        y = a[1] + (b[1] - a[1]) * t
        for (cx, cy, sx, sy, _name) in segments:
            dx = max(cx - sx / 2.0 - x, 0.0, x - (cx + sx / 2.0))
            dy = max(cy - sy / 2.0 - y, 0.0, y - (cy + sy / 2.0))
            d = math.hypot(dx, dy)
            if d < best:
                best = d
                where = (x, y)
            if best == 0.0:
                return 0.0, where
    return best, where


def free_run(segments, start, direction, clearance=0.16, max_len=6.0,
             step=0.02, bounds=None):
    """How far the robot can drive from ``start`` along ``direction`` [m].

    Stops at the first sample closer than ``clearance`` to a wall.  Used to
    pick a default goal for the straight-line P controller: the maze walls are
    axis aligned, so one of the four axis directions always has a free run.
    """
    dx, dy = direction
    n = int(max_len / step)
    last = 0.0
    for k in range(1, n + 1):
        d = k * step
        x = start[0] + dx * d
        y = start[1] + dy * d
        if bounds is not None:
            xmin, xmax, ymin, ymax = bounds
            if not (xmin < x < xmax and ymin < y < ymax):
                return last
        for (cx, cy, sx, sy, _name) in segments:
            gx = max(cx - sx / 2.0 - x, 0.0, x - (cx + sx / 2.0))
            gy = max(cy - sy / 2.0 - y, 0.0, y - (cy + sy / 2.0))
            if math.hypot(gx, gy) < clearance:
                return last
        last = d
    return last


def auto_goal(segments, start, clearance=0.16, margin=0.12):
    """Pick the far end of the longest free straight run from ``start``."""
    # stay inside the maze: the entrance/exit gaps would otherwise look free
    bounds = world_bounds(segments, margin=0.0)
    best = None
    for name, direction in (('north', (0.0, 1.0)), ('east', (1.0, 0.0)),
                            ('south', (0.0, -1.0)), ('west', (-1.0, 0.0))):
        length = free_run(segments, start, direction, clearance,
                          max_len=6.0, bounds=(bounds[0] + 0.05, bounds[1] - 0.05,
                                               bounds[2] + 0.05, bounds[3] - 0.05))
        if best is None or length > best[0]:
            best = (length, direction, name)
    length, direction, name = best
    if length <= margin + 0.05:
        raise RuntimeError(f'no free straight run from {start}')
    goal = (start[0] + direction[0] * (length - margin),
            start[1] + direction[1] * (length - margin))
    return goal, name, length



def route_length(points):
    return float(sum(math.dist(a, b) for a, b in zip(points, points[1:])))
